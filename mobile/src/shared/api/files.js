/**
 * Размер файла человеческими словами.
 *
 * Живёт в `shared`, потому что файлы есть не только у домашних заданий: материалы урока
 * показывают тот же размер тем же способом, а две реализации округления давали бы на
 * одном и том же файле «2,4 МБ» в одном экране и «2,5 МБ» в другом.
 */
export function sizeLabel(bytes) {
  if (!bytes || bytes <= 0) return null;
  if (bytes < 1024) return `${bytes} Б`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} КБ`;
  return `${(bytes / (1024 * 1024)).toFixed(1).replace('.', ',')} МБ`;
}
