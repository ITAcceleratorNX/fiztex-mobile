/**
 * Раскладка задачи генерации: подписи ожидания и итог.
 *
 * Формулировки фаз совпадают с вебовыми (`AiJobProgress`) дословно — учитель видит один
 * и тот же процесс с двух устройств, и «Составляю» на телефоне против «Генерирую» в
 * браузере читалось бы как два разных механизма.
 */

const PHASE_LABELS = {
  READING_MATERIALS: 'Читаю материалы урока',
  CALLING_MODEL: 'Составляю',
  APPLYING: 'Почти готово',
};

/**
 * Что происходит сейчас — словами (§2.1 плана: неподвижный спиннер за тридцать секунд
 * читается как «зависло»).
 *
 * Счётчик добавляется только когда шагов правда несколько: «1 из 1» — шум, и бэкенд его
 * для одиночного вызова не присылает вовсе.
 */
export function phaseLabel(job) {
  if (!job) return null;
  const base = PHASE_LABELS[job.phase] || 'Начинаю…';
  const { progressDone: done, progressTotal: total } = job;
  if (typeof done !== 'number' || typeof total !== 'number' || total <= 1) return base;
  return `${base} · ${done} из ${total}`;
}

/** Задача ещё идёт — по этому же признаку карточка решает, опрашивать ли дальше. */
export function isRunning(job) {
  return job?.status === 'PENDING' || job?.status === 'RUNNING';
}

/**
 * Итог задачи для шита — три исхода, и у каждого свои слова и своё действие.
 *
 * `awaitingDecision` на телефоне не предлагает выбора: сравнивать два конспекта на
 * экране в 390 точек — значит решать вслепую или скроллом. Врать «готово» тут тоже
 * нельзя — учитель ушёл бы публиковать изменение, которого нет.
 */
export function jobOutcome(job) {
  if (!job || isRunning(job)) return null;
  if (job.status === 'FAILED') {
    return {
      kind: 'failed',
      // Текст с бэкенда уже написан для человека (`HomeworkAiFailure`), поэтому идёт
      // как есть. Запасная строка — на случай задачи без сообщения.
      title: 'Не удалось сгенерировать',
      message: job.errorMessage || 'Попробуйте ещё раз или напишите задание сами.',
    };
  }
  /**
   * Готово, но в задание не легло. Основная причина — правки учителя после прошлой
   * генерации (`awaitingDecision`), но тот же исход даёт вытесненный результат, у
   * которого флага уже нет. Проверяем `applied`, а не флаг: для учителя это один и тот
   * же факт — его текст не тронут, — и назвать это «Готово» значит послать человека
   * публиковать изменение, которого нет.
   */
  if (!job.applied) {
    return {
      kind: 'awaiting',
      title: 'Вариант готов, но не применён',
      message:
        'Вы правили задание после прошлой генерации, и ваш текст остался на месте. '
        + 'Выберите, что оставить: подробное сравнение двух текстов — в веб-версии.',
    };
  }
  return {
    kind: 'done',
    title: 'Готово',
    // Предупреждение модели (нечитаемая ссылка, обрезанный текст) — часть успеха, а не
    // мелочь: учитель обязан узнать, что в конспект вошло не всё.
    message: job.warningMessage || null,
  };
}

/** Остаток квоты словами. Виден всегда: внезапный отказ по лимиту хуже заметного счётчика. */
export function quotaLabel(quota) {
  if (!quota || typeof quota.remaining !== 'number') return null;
  if (quota.enabled === false) return 'Генерация выключена администратором';
  if (quota.remaining <= 0) return 'Лимит генераций на сегодня исчерпан';
  return `Осталось ${quota.remaining} из ${quota.dailyQuota} на сегодня`;
}
