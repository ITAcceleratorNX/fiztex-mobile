import { request } from './client';
import { uuid } from '../uuid';

/**
 * Генерация содержимого задания моделью (ТЗ HOMEWORK-BE-006).
 *
 * <p>С телефона запускается и текст задания, и вопросы теста. Раньше тест был закрыт
 * намеренно — его результат это вопросы с ключом, а редактора вопросов в приложении не
 * было, и сгенерировать то, чего нельзя прочитать и поправить, значило отдать классу
 * непроверенное. Редактор появился (`TeacherHomeworkQuestionsScreen`), и причина исчезла:
 * генерация ведёт прямо в него.
 *
 * <p>Печатать десять вопросов с вариантами пальцем никто не станет — удобным создание
 * теста на телефоне делает именно связка «сгенерировал → прочитал → поправил».
 */
export const homeworkAiApi = {
  /** Остаток суточной квоты. Спрашивается при открытии шита. */
  quota: (token) => request('/api/homework/ai-quota', { token }),

  /**
   * Запуск. Отвечает `202` и строкой задачи — сама генерация идёт на сервере, поэтому
   * экран волен закрыться.
   *
   * `key` обязателен и создаётся один раз на открытие шита: повторное нажатие на плохой
   * сети не должно стать вторым платным вызовом модели.
   */
  start: (token, homeworkId, key, body) =>
    request(`/api/homework/${homeworkId}/ai-generations`, {
      method: 'POST',
      token,
      body,
      extraHeaders: { 'Idempotency-Key': key },
    }),

  /** Состояние одной задачи — по нему рисуется фаза ожидания. */
  job: (token, jobId) => request(`/api/homework/ai-generations/${jobId}`, { token }),

  /** Генерации задания: карточка узнаёт из них, что задача ещё идёт. */
  jobs: (token, homeworkId) => request(`/api/homework/${homeworkId}/ai-generations`, { token }),

  /**
   * Применить готовый вариант поверх своего текста.
   *
   * <p>Нужен ровно в одном случае: учитель правил задание после прошлой генерации, и
   * сервер не стал затирать его текст молча. Раньше телефон в этом месте отправлял в
   * веб-версию — «сравните там», — и генерация с телефона оказывалась наполовину
   * бесполезной: дошёл до результата и не смог им воспользоваться.
   */
  apply: (token, homeworkId, jobId) =>
    request(`/api/homework/${homeworkId}/ai-generations/${jobId}/apply`, {
      method: 'POST',
      token,
    }),

  /** Отказаться от варианта: свой текст остаётся, задача закрывается. */
  discard: (token, homeworkId, jobId) =>
    request(`/api/homework/${homeworkId}/ai-generations/${jobId}/discard`, {
      method: 'POST',
      token,
    }),
};

/** Ключ идемпотентности на одно открытие шита. */
export function newIdempotencyKey() {
  return uuid();
}
