import { request } from './client';

/**
 * Опросы — ученик и родитель отвечают на один и тот же контракт (backend contract final).
 *
 * <p>Респондент здесь один вне зависимости от роли: `GET /surveys/my` сам решает, что
 * вернуть, и у родителя с несколькими детьми это ровно одна анкета — ответ принадлежит
 * его аккаунту, а не ребёнку. Поэтому у методов ниже нет и не должно появиться `childId`:
 * заводить его значило бы повторять для опросов развилку по ребёнку, которая для этого
 * модуля бэкендом прямо не предусмотрена.
 *
 * <p>Опросы никогда не оцениваются — у варианта ответа нет признака правильности ни в
 * одном из ответов этого модуля.
 */
export const surveysApi = {
  /** Свои опросы — назначенные и уже пройденные, одной лентой без вкладок и фильтров. */
  list(token) {
    return request('/api/surveys/my', { token });
  },

  /**
   * Вопросы опроса вместе с уже сохранёнными черновиками ответов (`savedAnswers`).
   *
   * Черновик приезжает тем же ответом, а не отдельным запросом: прогресс восстанавливается
   * из него при каждом открытии экрана, в том числе после того, как приложение убили.
   */
  myQuestions(token, surveyId) {
    return request(`/api/surveys/${surveyId}/questions`, { token });
  },

  /**
   * Автосейв одного вопроса — апсерт на бэке. Вызывается на каждое изменение ответа, а
   * не один раз перед отправкой: серверный черновик и есть источник восстановления.
   *
   * @param {{questionId: number, selectedOptionIds?: number[], openText?: string}} answer
   */
  saveAnswer(token, surveyId, answer) {
    return request(`/api/surveys/${surveyId}/answers`, {
      method: 'PUT',
      body: answer,
      token,
    });
  },

  /**
   * Финальная отправка. `idempotencyToken` держит вызывающий в ref до успеха — повтор
   * с тем же токеном после обрыва сети возвращает уже принятый ответ вместо отказа, а не
   * создаёт вторую попытку сдать один и тот же опрос.
   */
  submit(token, surveyId, idempotencyToken) {
    return request(`/api/surveys/${surveyId}/submit`, {
      method: 'POST',
      body: idempotencyToken ? { idempotencyToken } : undefined,
      token,
    });
  },
};
