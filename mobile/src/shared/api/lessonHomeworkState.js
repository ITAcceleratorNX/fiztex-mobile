/**
 * Состояния блока «Домашнее задание» в карточке урока.
 *
 * Слова здесь дословно те же, что в вебе (`fiztex-web/src/lib/lessonHomeworkState.ts`):
 * учитель ставит отметку в одном приложении и видит её в другом, и «ДЗ не задано» против
 * «Задание не выдано» читались бы как два разных факта об одном уроке.
 *
 * Роль в расчёт не берётся: у ученика черновика не существует, и бэкенд отдаёт ему на
 * этом месте NOT_SPECIFIED — разница уже учтена в самом состоянии.
 */

const LABELS = {
  ASSIGNED: 'ДЗ задано',
  NOT_ASSIGNED: 'ДЗ не задано',
  DRAFT: 'Черновик. Не опубликовано',
  NOT_SPECIFIED: 'Домашнее задание пока не указано',
};

/** Пустая строка — состояния не пришло: в строке расписания его нет, только в карточке. */
export function homeworkStateLabel(state) {
  return LABELS[state] || '';
}

/**
 * Цвет `Pill` под состояние. Два финальных состояния спокойные: «не задано» — такой же
 * законный итог, как «задано», и красить его тревожно значило бы ругать учителя за
 * принятое решение. Незакрытые действия выделены — ради них ТЗ и написано.
 *
 * `success`, а не `green`: «green» в этой палитре исторически фирменный оранжевый.
 */
export function homeworkStateColor(state) {
  switch (state) {
    case 'ASSIGNED':
      return 'success';
    case 'DRAFT':
      return 'gold';
    case 'NOT_ASSIGNED':
      return 'gray';
    default:
      return 'blue';
  }
}

/**
 * Нужно ли действие учителя. Не «нет задания», а «сценарий не завершён»: черновик тоже
 * ждёт решения, хотя задание уже заведено.
 */
export function homeworkNeedsTeacherAction(state) {
  return state === 'NOT_SPECIFIED' || state === 'DRAFT';
}
