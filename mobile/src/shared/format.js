/**
 * Русское множественное число: `plural(3, ['материал', 'материала', 'материалов'])`.
 *
 * Заведено в `shared`, потому что то же правило уже переписано в проекте несколько раз
 * по месту. Новые экраны берут его отсюда; старые копии заменяются по мере того, как эти
 * файлы правят по другим поводам — массовая замена ради одной функции трогала бы полдюжины
 * не связанных между собой экранов.
 */
export function plural(n, forms) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return forms[1];
  return forms[2];
}

/** «3 материала» — число со словом в нужной форме. */
export function countLabel(n, forms) {
  return `${n} ${plural(n, forms)}`;
}
