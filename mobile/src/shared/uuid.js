/**
 * UUID v4 строкой.
 *
 * Своя реализация, потому что `crypto.randomUUID` в Hermes нет, а `expo-crypto` в
 * зависимостях нет тем более, и тянуть её ради одной строки не стоит.
 *
 * `Math.random` здесь достаточно: ключ идемпотентности не секрет и не токен — он лишь
 * должен не совпасть с другой попыткой. Совпадение к тому же не опасно: сервер сверяет
 * задание у найденной по ключу задачи и на чужое отвечает отказом, а не отдаёт её.
 */
export function uuid() {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (ch) => {
    const r = (Math.random() * 16) | 0;
    return (ch === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}
