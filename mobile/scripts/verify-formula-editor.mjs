import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { Script } from 'node:vm';
import { FORMULA_EDITOR_HTML as html } from '../src/shared/math/formulaEditorAsset.js';
import { insertFormulaAt, replaceFormulaAt, removeFormulaAt } from '../src/shared/math/formulaEditing.js';
const require = createRequire(resolve('../../fiztex-web/package.json'));
const mathlive = readFileSync(resolve(dirname(require.resolve('mathlive')), 'mathlive.min.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
assert.ok(html.includes(mathlive), 'MathLive bundle must survive embedding literally (including $ replacement patterns)');
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)];
assert.equal(scripts.length, 5, 'KaTeX, mhchem, renderer, MathLive and editor scripts are embedded once');
scripts.forEach(([_, source], index) => new Script(source, { filename: `offline-script-${index}.js` }));
assert.doesNotMatch(html, /<(?:script|link)\b[^>]*(?:src|href)=["']https?:/i);
const source = 'До $x^2$ между $\\ce{Fe^{2+}}$ после';
assert.equal(replaceFormulaAt(source, 1, '\\ce{Fe^{3+}}', false), 'До $x^2$ между $\\ce{Fe^{3+}}$ после');
assert.equal(removeFormulaAt(source, 1), 'До $x^2$ между после');
assert.equal(insertFormulaAt('До после', 3, '\\ce{H2O}', false).text, 'До $\\ce{H2O}$ после');
console.log('Offline assets compile; insertion, replacement and removal preserve surrounding formulas/text.');
