/** Local MathLive + KaTeX, the web palette and checks; no runtime CDN or remote fonts. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { KATEX_HTML } from '../src/shared/math/katexAsset.js';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const web = resolve(root, '../../fiztex-web');
const require = createRequire(resolve(web, 'package.json'));
const ts = require('typescript');
const mathliveRoot = dirname(require.resolve('mathlive'));
const escapeScript = text => text.replace(/<\/script/gi, '<\\/script');
function browserSource(file) {
  const source = readFileSync(resolve(web, 'src/lib', file), 'utf8').replace(/^import .*;\s*$/gm, '');
  return ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } })
    .outputText.replace(/^export\s+/gm, '').replace(/^\{\};\s*$/gm, '');
}
const catalog = JSON.parse(readFileSync(resolve(web, 'src/lib/formulaCatalog.json'), 'utf8'));
const shared = ['mathMarkup.ts', 'katexRender.ts', 'formulaChecks.ts', 'chemistryEditor.ts'].map(browserSource).join('\n');
const css = readFileSync(resolve(root, 'scripts/formula-editor/editor.css'), 'utf8');
const markup = readFileSync(resolve(root, 'scripts/formula-editor/editor.html'), 'utf8');
const runtime = readFileSync(resolve(root, 'scripts/formula-editor/editor.js'), 'utf8');
const script = `const katex=window.katex;\n${shared}\nconst FORMULA_CATALOG=${JSON.stringify(catalog)};\n${runtime}`;
const mathlive = readFileSync(resolve(mathliveRoot, 'mathlive.min.js'), 'utf8');
const mathliveFonts = readFileSync(resolve(mathliveRoot, 'mathlive-fonts.css'), 'utf8').replace(/url\(fonts\/([^)]*)\)/g,
  (_, name) => `url(data:font/woff2;base64,${readFileSync(resolve(mathliveRoot, 'fonts', name)).toString('base64')})`);
const html = KATEX_HTML.replace('</body>', () => `<style>${mathliveFonts}\n${css}</style>${markup}<script>${escapeScript(mathlive)}</script><script>${escapeScript(script)}</script></body>`);
writeFileSync(resolve(root, 'src/shared/math/formulaEditorAsset.js'), '// Generated by scripts/build-formula-editor.mjs. MathLive 0.110.0 (MIT), KaTeX/mhchem: katexAsset.js.\nexport const FORMULA_EDITOR_HTML = '+JSON.stringify(html)+';\n');
writeFileSync(resolve(root, 'src/shared/math/editor/MATHLIVE-LICENSE.txt'), readFileSync(resolve(mathliveRoot, 'LICENSE.txt')));
writeFileSync(resolve(root, 'src/shared/math/formulaEditing.js'), '// Generated from fiztex-web/src/lib/mathMarkup.ts by build-formula-editor.mjs.\n'+ts.transpileModule(readFileSync(resolve(web, 'src/lib/mathMarkup.ts'), 'utf8'), {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText);
console.log('Offline formula editor generated,', Buffer.byteLength(html), 'bytes');
